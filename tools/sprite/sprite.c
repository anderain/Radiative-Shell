/*
   sprite - convert a 24 bit BMP into a packed 2 bpp (four grey levels) array.

   Usage:
       sprite.exe test.bmp > test.c

   Output layout, matching the packed images in frontend/assets.h:

       const unsigned char IMG2BPP_TEST[] = {
           / * Width * / 12, / * Height * / 24,
           0x11, 0x22, ...
       };

   The two header bytes are followed by rows packed two bits per pixel, most
   significant pair first, so pixel 0 of a row lands in bits 7:6. Each row is
   padded up to a whole byte, the padding bits stay zero.

   Luminance is (r + g + b) / 3 and the four levels are
       0..63 black, 64..127 dark grey, 128..191 grey, 192..255 white.
*/

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define SPRITE_MAX_DIM      255     /* the header stores width and height in bytes */
#define SPRITE_BYTES_PER_ROW 16     /* how many bytes go on one source line */

/* Little endian readers. The BMP format is little endian regardless of the
   host, so these never depend on struct packing. */
static unsigned int SpriteReadU16(const unsigned char* p) {
    return (unsigned int)p[0] | ((unsigned int)p[1] << 8);
}

static unsigned long SpriteReadU32(const unsigned char* p) {
    return (unsigned long)p[0]
         | ((unsigned long)p[1] << 8)
         | ((unsigned long)p[2] << 16)
         | ((unsigned long)p[3] << 24);
}

/* Read a whole file into memory. Returns NULL and prints a message on failure.
   On success *pulSize holds the byte count. */
static unsigned char* SpriteReadFile(const char* pszName, unsigned long* pulSize) {
    FILE*          pFile;
    unsigned char* pBuf;
    unsigned long  ulSize;
    unsigned long  ulRead;

    pFile = fopen(pszName, "rb");
    if (!pFile) {
        fprintf(stderr, "sprite: cannot open '%s'\n", pszName);
        return NULL;
    }

    if (fseek(pFile, 0, SEEK_END) != 0) {
        fprintf(stderr, "sprite: cannot seek in '%s'\n", pszName);
        fclose(pFile);
        return NULL;
    }

    ulSize = (unsigned long)ftell(pFile);
    if (fseek(pFile, 0, SEEK_SET) != 0) {
        fprintf(stderr, "sprite: cannot rewind '%s'\n", pszName);
        fclose(pFile);
        return NULL;
    }

    if (ulSize == 0 || ulSize == (unsigned long)-1L) {
        fprintf(stderr, "sprite: '%s' is empty\n", pszName);
        fclose(pFile);
        return NULL;
    }

    pBuf = (unsigned char*)malloc(ulSize);
    if (!pBuf) {
        fprintf(stderr, "sprite: out of memory reading '%s'\n", pszName);
        fclose(pFile);
        return NULL;
    }

    ulRead = (unsigned long)fread(pBuf, 1, ulSize, pFile);
    fclose(pFile);

    if (ulRead != ulSize) {
        fprintf(stderr, "sprite: short read on '%s'\n", pszName);
        free(pBuf);
        return NULL;
    }

    *pulSize = ulSize;
    return pBuf;
}

/* Turn "dir\test.bmp" into "IMG2BPP_TEST". Characters outside A-Z and 0-9
   become underscores, everything is upper cased, and the extension is dropped. */
static void SpriteMakeSymbol(const char* pszPath, char* pszOut, int iOutSize) {
    const char* pBase;
    const char* pDot;
    int         iLen;
    int         i, o = 0;

    pBase = pszPath;
    {
        const char* p = pszPath;

        while (*p) {
            if (*p == '\\' || *p == '/' || *p == ':') {
                pBase = p + 1;
            }
            ++p;
        }
    }

    pDot = strrchr(pBase, '.');
    iLen = pDot ? (int)(pDot - pBase) : (int)strlen(pBase);

    /* Copy the "IMG2BPP_" prefix, leaving room for the terminator. */
    for (i = 0; i < (int)strlen("IMG2BPP_") && o < iOutSize - 1; ++i) {
        pszOut[o++] = "IMG2BPP_"[i];
    }

    for (i = 0; i < iLen && o < iOutSize - 1; ++i) {
        const char c = pBase[i];

        if ((c >= 'a' && c <= 'z')) {
            pszOut[o++] = (char)(c - 'a' + 'A');
        }
        else if ((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')) {
            pszOut[o++] = c;
        }
        else {
            pszOut[o++] = '_';
        }
    }

    pszOut[o] = 0;
}

/* Emit the array. Returns 0 on success. */
static int SpriteEmit(const unsigned char* pImage, int iWidth, int iHeight,
                      int iStride, const char* pszSymbol, const char* pszSource) {
    int y;
    int iCol = 0;
    int iLast;

    printf("/* Generated by sprite from %s */\n", pszSource);
    printf("/* %dx%d, 2 bpp, %d byte row stride */\n", iWidth, iHeight, iStride);
    printf("const unsigned char %s[] = {\n", pszSymbol);
    printf("    /* Width */ %d, /* Height */ %d,\n", iWidth, iHeight);

    for (y = 0; y < iHeight; ++y) {
        const unsigned char* pRow = pImage + (size_t)y * iStride;

        /* Emit only the bytes that actually carry pixels, so the padding bits
           at the end of a row never appear in the output. */
        iLast = (iWidth * 2 + 7) / 8;

        {
            int x;

            for (x = 0; x < iLast; ++x) {
                if (iCol == 0) {
                    printf("    ");
                }

                printf("0x%02X,", pRow[x]);
                ++iCol;

                if (iCol == SPRITE_BYTES_PER_ROW) {
                    printf("\n");
                    iCol = 0;
                }
                else {
                    printf(" ");
                }
            }
        }
    }

    if (iCol != 0) {
        printf("\n");
    }

    printf("};\n");
    return 0;
}

int main(int argc, char** argv) {
    unsigned char* pFile = NULL;
    unsigned long  ulSize = 0;
    unsigned long  ulOffBits;
    long           lWidth;
    long           lHeight;
    int            iTopDown = 0;
    int            iWidth;
    int            iHeight;
    unsigned int   uiBitCount;
    unsigned long  ulCompression;
    unsigned long  ulRowSize;
    int            iStride;
    unsigned char* pImage = NULL;
    unsigned char* pBits;
    char           szSymbol[64];
    int            y, x;

    if (argc != 2) {
        fprintf(stderr, "sprite - 24 bit BMP to packed 2 bpp array\n");
        fprintf(stderr, "usage: sprite.exe input.bmp > output.c\n");
        return 2;
    }

    pFile = SpriteReadFile(argv[1], &ulSize);
    if (!pFile) {
        return 1;
    }

    if (ulSize < 54 || pFile[0] != 'B' || pFile[1] != 'M') {
        fprintf(stderr, "sprite: '%s' is not a BMP file\n", argv[1]);
        free(pFile);
        return 1;
    }

    if (SpriteReadU32(pFile + 0x0E) < 40) {
        fprintf(stderr, "sprite: '%s' uses an old style header, not supported\n", argv[1]);
        free(pFile);
        return 1;
    }

    ulOffBits    = SpriteReadU32(pFile + 0x0A);
    lWidth       = (long)SpriteReadU32(pFile + 0x12);
    uiBitCount   = SpriteReadU16(pFile + 0x1C);
    ulCompression = SpriteReadU32(pFile + 0x1E);

    /* biHeight is signed: a negative value means the rows are stored top
       down, which some tools emit. */
    {
        const long lRawHeight = (long)SpriteReadU32(pFile + 0x16);

        if (lRawHeight < 0) {
            iTopDown = 1;
            lHeight = -lRawHeight;
        }
        else {
            lHeight = lRawHeight;
        }
    }

    if (uiBitCount != 24) {
        fprintf(stderr, "sprite: '%s' is %u bpp, only 24 bit is supported\n",
                argv[1], uiBitCount);
        free(pFile);
        return 1;
    }

    if (ulCompression != 0) {
        fprintf(stderr, "sprite: '%s' is compressed, only BI_RGB is supported\n", argv[1]);
        free(pFile);
        return 1;
    }

    if (lWidth <= 0 || lHeight <= 0) {
        fprintf(stderr, "sprite: '%s' has an empty image (%ldx%ld)\n",
                argv[1], lWidth, lHeight);
        free(pFile);
        return 1;
    }

    if (lWidth > SPRITE_MAX_DIM || lHeight > SPRITE_MAX_DIM) {
        fprintf(stderr,
                "sprite: '%s' is %ldx%ld, but the 2 byte header only holds 1..%d\n",
                argv[1], lWidth, lHeight, SPRITE_MAX_DIM);
        free(pFile);
        return 1;
    }

    iWidth  = (int)lWidth;
    iHeight = (int)lHeight;

    /* BMP rows are padded to a multiple of four bytes. */
    ulRowSize = ((unsigned long)iWidth * 3UL + 3UL) / 4UL * 4UL;

    if (ulOffBits + ulRowSize * (unsigned long)iHeight > ulSize) {
        fprintf(stderr, "sprite: '%s' is truncated, pixel data runs past the end\n",
                argv[1]);
        free(pFile);
        return 1;
    }

    iStride = (iWidth * 2 + 7) / 8;
    pImage = (unsigned char*)malloc((size_t)iStride * iHeight);
    if (!pImage) {
        fprintf(stderr, "sprite: out of memory\n");
        free(pFile);
        return 1;
    }

    memset(pImage, 0, (size_t)iStride * iHeight);
    pBits = pFile + ulOffBits;

    for (y = 0; y < iHeight; ++y) {
        /* Row 0 of the output is always the top of the image. */
        const int            iSrcRow = iTopDown ? y : (iHeight - 1 - y);
        const unsigned char* pSrc = pBits + (size_t)iSrcRow * ulRowSize;
        unsigned char*       pDst = pImage + (size_t)y * iStride;

        for (x = 0; x < iWidth; ++x) {
            const unsigned int b = pSrc[x * 3 + 0];
            const unsigned int g = pSrc[x * 3 + 1];
            const unsigned int r = pSrc[x * 3 + 2];
            const unsigned int luma = (r + g + b) / 3;
            const unsigned int level = luma >> 6;   /* 0..3 */

            /* Most significant pair first: pixel 0 lands in bits 7:6. */
            pDst[x >> 2] |= (unsigned char)(level << (6 - (x & 3) * 2));
        }
    }

    SpriteMakeSymbol(argv[1], szSymbol, (int)sizeof(szSymbol));

    fprintf(stderr, "sprite: %s -> %s, %dx%d, stride %d, %d bytes\n",
            argv[1], szSymbol, iWidth, iHeight, iStride, iStride * iHeight);

    SpriteEmit(pImage, iWidth, iHeight, iStride, szSymbol, argv[1]);

    free(pImage);
    free(pFile);
    return 0;
}
